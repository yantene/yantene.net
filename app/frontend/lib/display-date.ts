/**
 * ISO 日付文字列 ("YYYY-MM-DD") を、画面に出す形にする。
 *
 * **サイト全体で 1 つの書式に揃える。** 記事の日付も、プロフィールの生年月日も
 * `2026.09.15` の形で出す。場所ごとに書き分けると、同じ日付が画面のどこにあるかで
 * 別の姿になる。
 *
 * 言語で切り替えない。数字だけの表記はどちらの言語でも同じに読め、切り替えると
 * 桁の揃え (`tabular-nums`) が言語によって効いたり効かなかったりする。
 *
 * **`new Date()` を通さない。** ISO 日付を `Date` に食わせると UTC の 0 時として
 * 解釈されるので、UTC より西の時間帯では前日になる。SSR (UTC) と手元のブラウザで
 * 1 日ずれ、hydration の食い違いとして表に出る。字の置き換えだけで済ませる。
 */
export function toDisplayDate(iso: string): string {
  return iso.replaceAll("-", ".");
}
