/*
 * ロゴの組み方。胸から上のキャラクターとロゴタイプを横に並べた姿の寸法。
 *
 * **ロゴは合成済みの 1 枚では持たない。** 以前は `yantene-logo.svg` に絵を写して持って
 * いたが、写しは必ず古びる — キャラクターの絵を差し替えたとき、ヘッダーと OG カードだけが
 * 旧い姿で取り残された ([#527](https://github.com/yantene/yantene.net/issues/527))。
 * いまは素材 2 つをこの寸法で並べるだけで、絵の在り処は 1 つずつになっている。
 *
 * **キャラクターは胸から上だけを出す** (#544)。全身だと 40px の帯で頭が 17px ほどに
 * なり、何の絵か読めなかった。切り出しは素材を写さず、入れ子の `<svg>` の viewBox で
 * 素材の上端から窓を開けるだけにしてある。
 *
 * 座標はキャラクターの素材のまま使う (高さ 170 がロゴの高さ)。ロゴタイプはそこへ
 * 縮めて置く。倍率は全身のころと同じ `170 / 256.771` で、帯の中での字の大きさ
 * (40px の帯で 26px) を変えないため。右端がちょうど `LOGO_VIEW_BOX.width` に収まる
 * ことが確かめになっている (`197 + 409.394 = 606.394`)。
 *
 * ⚠️ **並びの詰め方は意匠である。** 指さす手の先 (x 171.6) と最初の字の間は約 25 units。
 * 字どうしの間より広いのは、実際に出る大きさ (ヘッダーで 40px、OG カードで 64px) で
 * 詰めると手が字に触れて見えるため。素材を差し替えて輪郭が変わったら、この隙間を目で
 * 見直すこと。
 */

/** 並べ終えた姿の viewBox。 */
export const LOGO_VIEW_BOX = { width: 606.394, height: 170 } as const;

/** 縦横比 (幅 / 高さ)。`img` に preserveAspectRatio を渡せない OG カードが使う。 */
export const LOGO_ASPECT = LOGO_VIEW_BOX.width / LOGO_VIEW_BOX.height;

/**
 * やんてねくんの胸から上。素材 (`0 0 188.395 256.774`) の上端から高さ 170 の窓を開ける。
 *
 * ⚠️ **170 は抱えたノートパソコンの `@` が入りきるところ。** ノートは y 119 から下に
 * あり、130〜150 で切ると角だけが覗いて、40px では絵の欠けに見える。頭と肩だけ
 * (〜128) まで詰めると顔は大きくなるが、バストアップではなく顔の寄りになる
 * (それは `public/icons/profile.svg` の役)。
 */
export const LOGO_CHARACTER = {
  x: 0,
  y: 0,
  width: 188.395,
  height: 170,
  viewBox: "0 0 188.395 170",
} as const;

/**
 * 「やんてね」の字形。
 *
 * 縦はキャラクターの窓の真ん中に着く。全身のころは足が地面に着く分だけ上に寄せていたが、
 * 胸から上には寄せる理由になる足が無い。
 */
export const LOGO_LOGOTYPE = { x: 197, y: 29.294, width: 409.394, height: 111.412 } as const;
