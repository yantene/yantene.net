/**
 * 3 段の精度の日 (`2011` / `2011-06` / `2011-06-04`) と、その終わりから、札の字を作る。
 *
 * 点ならそのまま。終わりがあるときは**始まりと重なる位を畳んで**出す。
 *
 * | 始まり     | 終わり     | 札                         |
 * | ---------- | ---------- | -------------------------- |
 * | 2012-08-14 | 2012-08-18 | `2012-08-14 〜 18`         |
 * | 2012-08-14 | 2012-09-02 | `2012-08-14 〜 09-02`      |
 * | 2012-12-28 | 2013-01-03 | `2012-12-28 〜 2013-01-03` |
 * | 2011       | 2013       | `2011 〜 2013`             |
 *
 * 畳まずに両端を書くと、5 日間の合宿の札が 24 字になって本文より目立つ。**最後の位は
 * 必ず残す** (`2012-08-14 〜 ` のような尻切れを作らない)。
 *
 * 経歴の年表と作品の時期が同じ書式の日を持つので、札の作り方もここに 1 つだけ置く。
 */
export function spanStamp(from: string, until: string | null): string {
  if (until === null) return from;

  const start = from.split("-");
  const end = until.split("-");
  // 始まりと違いの出る最初の位。精度は同じなので、必ずどこかで違う。
  const differs = start.findIndex((part, index) => part !== end[index]);
  const keepFrom = differs === -1 ? start.length - 1 : differs;

  return `${from} 〜 ${end.slice(keepFrom).join("-")}`;
}
